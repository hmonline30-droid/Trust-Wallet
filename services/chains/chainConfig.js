export function getTreasuryAddress(chainId) {
  const meta = CHAIN_METADATA[chainId];
  if (!meta) return null;
  const fromEnv = process.env[meta.treasuryEnv]?.trim();
  return fromEnv || meta.defaultTreasury;
}

export function getAcceptedTreasuryAddresses(chainId) {
  const meta = CHAIN_METADATA[chainId];
  if (!meta) return [];
  const list = [getTreasuryAddress(chainId)];
  if (meta.legacyTreasuryEnv) {
    const legacy = process.env[meta.legacyTreasuryEnv]?.trim() || meta.defaultLegacyTreasury;
    if (legacy) list.push(legacy);
  }
  return list.filter(Boolean);
}

export function getHotWalletSecret(chainId) {
  const meta = CHAIN_METADATA[chainId];
  if (!meta) return null;
  return process.env[meta.hotWalletEnv]?.trim() || null;
}
